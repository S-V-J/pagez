// FILE: frontend/src/components/ui/table.tsx
//
// SYSTEMIC ROLE:
//   Semantic table primitives for Pagez data-heavy surfaces.
//
//   Used by:
//   - Superadmin tenant tables (P16)
//   - Booking queues (P09)
//   - Service catalog lists (P08)
//   - Analytics tables (P15)
//   - Payment ledger views (P10)
//   - Subscription member tables (P11)
//   - Ad campaign tables (P12)
//
//   ACCESSIBILITY CONTRACT:
//   - Uses native table semantics: table, thead, tbody, tfoot, tr, th, td, caption.
//   - TableHead should be used for column headers.
//   - TableRow supports data-state="selected" for selectable rows.
//   - TableCaption provides accessible table description.
//
//   DESIGN TOKEN CONTRACT:
//   - Border uses --pagez-border.
//   - Muted hover uses --pagez-muted.
//   - Foreground/muted-foreground utilities are semantic.
//   - Dark mode and tenant overrides are automatic.

import type * as React from "react";

import { cn } from "@/lib/utils";

function Table({ className, ...props }: React.ComponentProps<"table">) {
  return (
    <div
      data-slot="table-wrapper"
      className="relative w-full overflow-x-auto"
    >
      <table
        data-slot="table"
        className={cn("w-full caption-bottom text-sm", className)}
        {...props}
      />
    </div>
  );
}

function TableHeader({ className, ...props }: React.ComponentProps<"thead">) {
  return (
    <thead
      data-slot="table-header"
      className={cn("", className)}
      {...props}
    />
  );
}

function TableBody({ className, ...props }: React.ComponentProps<"tbody">) {
  return (
    <tbody
      data-slot="table-body"
      className={cn("", className)}
      {...props}
    />
  );
}

function TableFooter({ className, ...props }: React.ComponentProps<"tfoot">) {
  return (
    <tfoot
      data-slot="table-footer"
      className={cn(
        "border-t border-border bg-muted/50 font-medium [&>tr]:last:border-b-0",
        className,
      )}
      {...props}
    />
  );
}

function TableRow({ className, ...props }: React.ComponentProps<"tr">) {
  return (
    <tr
      data-slot="table-row"
      className={cn(
        "border-b border-border transition-colors duration-[var(--pagez-duration-fast)] ease-[var(--pagez-ease-out)] hover:bg-muted/50 data-[state=selected]:bg-muted",
        className,
      )}
      {...props}
    />
  );
}

function TableHead({ className, ...props }: React.ComponentProps<"th">) {
  return (
    <th
      data-slot="table-head"
      className={cn(
        "h-12 px-4 text-left align-middle font-medium text-muted-foreground",
        className,
      )}
      {...props}
    />
  );
}

function TableCell({ className, ...props }: React.ComponentProps<"td">) {
  return (
    <td
      data-slot="table-cell"
      className={cn("p-4 align-middle", className)}
      {...props}
    />
  );
}

function TableCaption({
  className,
  ...props
}: React.ComponentProps<"caption">) {
  return (
    <caption
      data-slot="table-caption"
      className={cn("mt-4 text-sm text-muted-foreground", className)}
      {...props}
    />
  );
}

export {
  Table,
  TableBody,
  TableCaption,
  TableCell,
  TableFooter,
  TableHead,
  TableHeader,
  TableRow,
};
